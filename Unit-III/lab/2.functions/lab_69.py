# Lab No. 69: Passing Arguments to a Function
#
# Objective:
# To understand how to pass arguments to a function using parameters.

# Program

def greet(name):  # 'name' is a parameter
    print(f"Hello, {name}!")


greet("Shyam")  # "Shyam" is an argument


# -----------------------------
# Key Points
# -----------------------------
# 1. A parameter is a variable defined in the function definition.
# 2. An argument is the actual value passed to a function.
# 3. name is the parameter.
# 4. "Shyam" is the argument.
# 5. The argument is assigned to the parameter name.
# 6. f-strings are used to insert values into strings.
