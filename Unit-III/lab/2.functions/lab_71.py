# Lab No. 71: Function with Multiple Parameters and Return Value
#
# Objective:
# To understand how to pass multiple arguments to a function and
# return the result using the return statement.

# Program

def multiply(x, y):
    return x * y


result = multiply(3, 4)

print(result)


# -----------------------------
# Key Points
# -----------------------------
# 1. x and y are parameters of the function.
# 2. 3 and 4 are arguments passed to the function.
# 3. return x * y calculates and returns the product.
# 4. multiply(3, 4) returns 12.
# 5. The returned value is stored in result.
# 6. A function can have multiple parameters.
