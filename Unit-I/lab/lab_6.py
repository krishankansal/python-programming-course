# # Lab 6: Comparison (Relational) Operators in Pytho
# Objective : To learn how to compare values using Python's comparison (relational) operators and interpret the Boolean (True or False) results.

num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))      

print("\nComparison Operations")
print("---------------------")      

print("Equal to (==)          :", num1 == num2)
print("Not equal to (!=)      :", num1 != num2)
print("Greater than (>)       :", num1 > num2)      
print("Less than (<)          :", num1 < num2)
print("Greater than or equal to (>=) :", num1 >= num2)
print("Less than or equal to (<=)    :", num1 <= num2)

# Key Notes
# 1. Comparison operators always return a Boolean value (True or False).
# 2. They are commonly used in decision-making and looping statements.
# 3. Numbers, strings, and many other data types can be compared.
# 4. The equality operator is ==, whereas the assignment operator is =. 



