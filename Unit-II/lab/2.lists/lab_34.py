# Lab 34: Introduction to Lists in Python
# Objective:
# To understand lists in Python and learn how to create and display lists
# containing different types of elements.

# 1. Creating a list of strings
students = ["Alice", "Bob", "Charlie", "David"]

print("List of Students:")
print(students)

# 2. Creating a list of numbers
marks = [85, 72, 91, 68, 77]

print("\nList of Marks:")
print(marks)

# 3. Creating a list with different data types
student = ["Alice", 21, 8.5, True]

print("\nList with Different Data Types:")
print(student)

# 4. Creating an empty list
subjects = []

print("\nEmpty List:")
print(subjects)

# 5. Creating a list with duplicate values
numbers = [10, 20, 10, 30, 20, 40]

print("\nList with Duplicate Values:")
print(numbers)

# Key Notes
# 1. A list is an ordered collection of elements in Python.
# 2. Lists are created using square brackets [ ].
# 3. A list can contain elements of different data types.
# 4. Lists can contain duplicate values.
# 5. Lists are mutable, which means their elements can be changed.
# 6. Each element in a list has a position called an index.